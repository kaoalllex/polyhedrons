"""Export the witnesses listed in witnesses.json to the site viewer (root index.html).

Each witness is re-verified exactly (verification/verify_candidate.py, expected genus) before export; its
vertices are the triple points of its face planes, its faces the corner cycles of its map. The generated
block replaces the text between the LAB markers in index.html.

Usage: python3 export_site.py           write index.html
       python3 export_site.py --check   exit 1 if index.html is not in sync (used by verify_all)"""
import html
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
SITE = os.path.normpath(os.path.join(ROOT, '..', '..', 'index.html'))
BLOB = 'https://github.com/kaoalllex/polyhedrons/blob/main/research/12-faced-polyhedron/'
sys.path.insert(0, os.path.join(ROOT, 'code'))
sys.path.insert(0, os.path.join(ROOT, 'verification'))
from verify_candidate import _links, verify_file  # noqa: E402

COLORS = [5686783, 16757844, 10259455, 5562289, 16740764, 7907583, 16765286, 6809824, 16754027, 9359868,
          14262783, 9889459]
MARKS = {'options': ('    <!-- LAB-OPTIONS-BEGIN (generated by research/12-faced-polyhedron/witnesses/export_site.py) -->\n',
                     '    <!-- LAB-OPTIONS-END -->\n'),
         'models': ('  // LAB-MODELS-BEGIN (generated by research/12-faced-polyhedron/witnesses/export_site.py)\n',
                    '  // LAB-MODELS-END\n')}


def planes_links(d):
    if 'solid' in d:
        import solid_first as SF
        from gauss_degree import coherent_triangles, links_from
        A = SF.Arrangement(np.array(d['planes'], float))
        return A.H, links_from(coherent_triangles(SF.extract_map(A, {tuple(x) for x in d['solid']})), A.n)
    return np.array(d['planes'], float), _links(d)


def model(w):
    path = os.path.join(ROOT, w['source'])
    (rep,) = verify_file(path)
    V, E, F, chi = rep['V_E_F_chi']
    assert rep['PASS'] and (2 - chi) // 2 == w['genus'], (w['id'], rep)
    H, L = planes_links(json.load(open(path)))
    idx, verts, faces = {}, [], []
    for X in range(len(H)):
        cyc = []
        for i in range(len(L[X])):
            t = tuple(sorted((X, L[X][i], L[X][(i + 1) % len(L[X])])))
            if t not in idx:
                idx[t] = len(verts) + 1
                p = np.linalg.solve(H[list(t), :3], -H[list(t), 3])
                verts.append([round(float(c), 6) for c in p])
            cyc.append(idx[t])
        faces.append(cyc)
    use = {}
    for fi, f in enumerate(faces):
        for a, b in zip(f, f[1:] + f[:1]):
            use.setdefault(frozenset((a, b)), []).append((a, b))
    assert all(len(u) == 2 and u[0] == u[1][::-1] for u in use.values()), w['id'] + ': incoherent face cycles'
    pairs = sum(1 for X in range(F) for Y in range(X + 1, F) if Y in L[X])
    sub = ('<a href="%s%s" target="_blank" rel="noopener noreferrer">Our search · source file</a> · exactly verified · '
           'genus %d · %d of %d face pairs adjacent · partial object, not a solution'
           % (BLOB, w["source"], w["genus"], pairs, F * (F - 1) // 2))
    return {'id': w['id'], 'title': w['title'], 'subtitle': sub, 'vertices': verts, 'faces': faces,
            'colors': COLORS[:F]}, (V, len(use), F)


def blocks():
    W = json.load(open(os.path.join(HERE, 'witnesses.json')))
    opts = '    <optgroup label="Our search · partial objects">\n%s    </optgroup>\n' % ''.join(
        '      <option value="%s">%s</option>\n' % (w['id'], html.escape(w['label'])) for w in W)
    mods = ''
    for w in W:
        m, (V, E, F) = model(w)
        assert V - E + F == 2 - 2 * w['genus']
        mods += '  %s: %s,\n' % (w['id'], json.dumps(m, separators=(',', ':')))
    return {'options': opts, 'models': mods}


def splice(text, key, body):
    a, b = MARKS[key]
    i, j = text.index(a) + len(a), text.index(b)
    return text[:i] + body + text[j:]


def main():
    text = open(SITE).read()
    new = text
    for k, body in blocks().items():
        new = splice(new, k, body)
    if '--check' in sys.argv:
        print('index.html lab models in sync' if new == text else 'index.html lab models OUT OF SYNC')
        sys.exit(0 if new == text else 1)
    open(SITE, 'w').write(new)
    print('wrote', SITE)


if __name__ == '__main__':
    main()
