"""E-261119-02 stage-B inputs (PLAN amendment 2): per-map symmetric formula records for the E-261103-03 runner.

The maps and their rotations come from the committed stage-A records (results/stageA/*/results.jsonl). A record holds
the map's links (vertex = face, cyclic neighbour list, labels = the canonical code's vertex labels), the face
permutation of the rotation, and the chart: C3 and free C2 uniform in the standard chart, C2 4 x 2 + 1 plane-only in a
moved chart (tranche.submap_formula). One record per map and rotation group (a map can carry several).

maps/pricing.json, queue_pricing.json   (9, 4): up to PRICE_PER_STRATUM maps per stratum and family, frozen draw
maps/rung_9_3.json, queue_rung_9_3.json  (9, 3): the 8 C3 and 24 C2 4 x 2 + 1 classes (decided UNSAT, STATUS 3d)
maps/rung_8_3.json, queue_rung_8_3.json  (8, 3): Roest-Vigh's and Mizhaev's maps under every free C2 they carry
maps/pass1.json, queue_pass1.json        (9, 4), amendment 3: every map of both lists, cap PASS1_CAP; the maps file
                                         (16 MB) is not committed: this script rebuilds it, the queue pins its SHA-256
Usage: stageb.py [--check]"""
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import random
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import symcensus as S  # noqa: E402

ROOT = S.ROOT
STAGE_A = HERE / 'results/stageA'
RUNNER = ROOT / 'experiments/E-261103-03-s5-exact-decision-8-2-9-3'
CONTROL_F9 = 'control_f9.json'
DRAW_SEED, PRICE_PER_STRATUM, SHARDS = 2611200201, 3, 10
SOLVER_CAP, BRIDGE_CAP, PASS1_CAP = 600, 360, 30
CHART = {'C3': (False, 'C3 3+3+3, uniform, standard chart'), 'C2f': (True, 'C2 4 x 2 + 1, plane-only, moved chart'),
         'C2': (False, 'C2 free, uniform, standard chart')}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def code_sha(code):
    return hashlib.sha256(json.dumps(code, separators=(',', ':')).encode()).hexdigest()


def kind(name):
    return 'C2f' if name.startswith('C2f') else name.split('_')[0]


def maps_of(name):
    """code (JSON text) -> (stratum set, set of dart actions) for one stage-A configuration."""
    out = defaultdict(lambda: (set(), set()))
    for r in S.records(STAGE_A):
        if r['config'] == name:
            for mp in r['maps']:
                st, acts = out[json.dumps(mp['code'])]
                st.add('b%d m%s' % (r['b'], ''.join(map(str, r['mult_pattern'])))); acts.add(tuple(mp['action']))
    return out


def links_and_groups(code, actions, F):
    """Links keyed by the code's vertex labels and the distinct cyclic groups generated by the actions on vertices."""
    M = S.census.from_code([tuple(x) for x in code])
    cyc, _ = M.vertices()
    links = [None] * F
    for c in cyc:
        v = M.tail[c[0]]
        assert all(M.tail[d] == v for d in c) and links[v] is None
        links[v] = [M.head(d) for d in c]
    groups = {}
    for act in sorted(actions):
        g = [None] * F
        for d, e in enumerate(act):
            assert g[M.tail[d]] in (None, M.tail[e])
            g[M.tail[d]] = M.tail[e]
        k, h = [tuple(range(F))], tuple(g)
        while h != tuple(range(F)):
            k.append(h); h = tuple(h[x] for x in g)
        groups.setdefault(frozenset(k), g)
    return links, [groups[k] for k in sorted(groups, key=lambda k: sorted(k))]


def records_for(name, codes, extra=None):
    F = S.CONFIGS[name][0]; planes_only, group = CHART[kind(name)]
    data = maps_of(name); out = []
    for k in codes:
        strata, actions = data[k]
        code = json.loads(k)
        links, gens = links_and_groups(code, actions, F)
        for j, g in enumerate(gens):
            out.append(dict(config=name, stratum=sorted(strata), links=links, canonical_sha256=code_sha(code),
                            group_index=j, groups_on_map=len(gens), sym_generator=g, sym_planes_only=planes_only,
                            sym_group=group, seed=0, **(extra or {}).get(k, {})))
    return out


def pricing():
    rng = random.Random(DRAW_SEED); recs = []
    for name in ('C3_9_4', 'C2f_9_4'):
        by = defaultdict(list)
        for k, (strata, _) in maps_of(name).items():
            assert len(strata) == 1, 'a (9, 4) map in one stratum (README stage A)'
            by[next(iter(strata))].append(k)
        for st in sorted(by):
            recs += records_for(name, sorted(rng.sample(sorted(by[st]), min(PRICE_PER_STRATUM, len(by[st])))))
    return dict(note='E-261119-02 amendment 2: pricing draw, %d per stratum, seed %d' % (PRICE_PER_STRATUM, DRAW_SEED),
                maps=recs)


def rung_9_3():
    return dict(note='E-261119-02 amendment 2: (9, 3) rung, every symmetric class (expected UNSAT-SOLVER, STATUS 3d)',
                maps=records_for('C3_9_3', sorted(maps_of('C3_9_3'))) + records_for('C2f_9_3', sorted(maps_of('C2f_9_3'))))


def pass1():
    recs = [r for name in ('C3_9_4', 'C2f_9_4') for r in records_for(name, sorted(maps_of(name)))]
    return dict(note='E-261119-02 amendment 3: pass 1, every (9, 4) map of both lists', maps=recs)


def rung_8_3():
    known = {v: {'known': k} for k, v in S.known_8_3_codes().items()}
    return dict(note='E-261119-02 amendment 2: (8, 3) rung, the two known maps under every free C2 (expected SAT)',
                maps=records_for('C2_8_3', sorted(known), known))


def queue(records_file, records, case, solver_cap, controls):
    rows = []
    if controls:
        c = dict(control_sha256=sha(RUNNER / CONTROL_F9), solver_cap=60, checker_cap=120)
        rows += [dict(index=f'control-f9{neg}-s{s}', control=kind_, **c)
                 for neg, kind_ in [('', 'positive'), ('-neg', 'negative')] for s in range(SHARDS)]
    rows += [dict(index=i, seed=r['seed'], solver_cap=solver_cap, checker_cap=BRIDGE_CAP,
                  canonical_sha256=r['canonical_sha256']) for i, r in enumerate(records)]
    data = dict(target='E-261119-02 stage B %s, kissat seed 0, no proof' % records_file.stem, target_check='all-pairs',
                case=list(case), maps_file=str(records_file.relative_to(ROOT)), maps_sha256=sha(records_file),
                shards=SHARDS, maps=rows)
    if controls:
        data['control_file'] = CONTROL_F9
    return data


def main():
    check = '--check' in sys.argv
    built = [('pricing', pricing(), (9, 4), True, SOLVER_CAP), ('rung_9_3', rung_9_3(), (9, 3), True, SOLVER_CAP),
             ('rung_8_3', rung_8_3(), (8, 3), False, SOLVER_CAP), ('pass1', pass1(), (9, 4), True, PASS1_CAP)]
    for stem, data, case, controls, cap in built:
        path = HERE / 'maps' / (stem + '.json'); qpath = HERE / ('queue_%s.json' % stem)
        indent = None if stem == 'pass1' else 1  # compact: 12562 records
        text = json.dumps(data, indent=indent) + '\n'
        if check and stem != 'pass1':  # the uncommitted pass-1 maps file is rebuilt; its queue pins the hash
            assert path.read_text() == text, path
        else:
            path.parent.mkdir(exist_ok=True); path.write_text(text)
        q = json.dumps(queue(path, data['maps'], case, cap, controls), indent=indent) + '\n'
        if check:
            assert qpath.read_text() == q, qpath
        else:
            qpath.write_text(q)
        print(stem, 'records', len(data['maps']), 'maps sha256', sha(path), 'queue sha256', sha(qpath))


if __name__ == '__main__':
    main()
